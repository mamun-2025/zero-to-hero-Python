
# Assignment Operators in Python
"""
The python operators are used to perform operations on values and varables.
These are the special symbols that carry out arithmetic, and bitwise computations.
The value the operator operates on is known as the Operand.
Assignement Operators are used to assign values to variables.
This operator is used to assign the value of the right side of the expression to the left side operand.
"""
# Assigning values using 
# Assignment Operator
a = 3
b = 5

c = a + b 

print(c)

# 1. Addition Assignment Operator
a = 3 
b = 5

a += b # a = a + b 
print(a)

# 2. Subtraction Assignment Operator
a = 3 
b = 5

a -= b # a = a - b
print(a)

# 3. Multiplication Assignment Operator 
a = 3 
b = 5

a *= b # a = a * b
print(a)

# 4. Division Assignment Operator
a = 3 
b = 5

a /= b # a = a / b
print(a)

# 5. Modulus Assignment Operator
a = 3
b = 5

a %= b # a = a % b
print(a)

# 6. Floor Division Assignment Operator
a = 3
b = 5

a //= b # a = a // b
print(a)

# 7. Exponentiation Assignment Operator
a = 3 
b = 5

a **= b # a = a ** b
print(a)
