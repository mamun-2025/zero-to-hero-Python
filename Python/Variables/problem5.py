
# 1. Join a name and age together 
# We convert age into string using str()
name = "Mamun"
age = 25

print(name + " is " + str(age) + " years old.")

# 2. Add two numbers taken as string
# Strings cannot do mathematical addition directly
# We must convert them into integers

a = "10"
b = "20"

print(int(a) + int(b))

