
# 1. swap two numbers
# Swapping means exchanging values
a = 10 
b = 20

a, b = b, a
print("a =", a)
print("b =", b)

# 2. Swap two numbers using a third variable
# A temporary variable stores one value during swapping
a = 5
b = 8

temp = a 
a = b 
b = temp 

print("a =", a)
print("b =", b)

# 3. Swap three variables step by step
# Swapping means exhanging values
# a goes to b 
# b goes to c 
# c goes to a 

a = 10
b = 20
c = 30

temp = a 
a = b 
b = c
c = temp 

print("a =", a)
print("b =", b)
print("c =", c)
