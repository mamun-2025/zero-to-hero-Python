
# 1. Convert a string number into an integer
# Sometimes numbers come as text (string).
# We use int() to convert string into integer
num = "25"
converted_num = int(num)
print(converted_num)
print(type(converted_num))

# 2. Convert an integer into a string
# We use str() to convert a number into text
age = 18
converted_age = str(age)
print(converted_age)
print(type(converted_age))

# 3. Convert float into int
# float means decimal number
# int() removes the decimal part
num = 10.99
converted_num = int(num)
print(converted_num)
print(type(converted_num))

# 4. Convert integer into float
# We use float() to convert integer into decimal number.
num = 10
converted_num = float(num)
print(converted_num)

